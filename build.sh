#!/bin/bash
# Build the APK with only the Android SDK command-line tools (no Gradle needed).
set -euo pipefail
cd "$(dirname "$0")"

SDK="${ANDROID_HOME:-$HOME/Library/Android/sdk}"
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
JAR="$SDK/platforms/android-36/android.jar"
[ -f "$JAR" ] || JAR="$SDK/platforms/$(ls "$SDK/platforms" | grep -E '^android-[0-9]+$' | sort -V | tail -1)/android.jar"
# Two builds from the same code:
#   ./build.sh dev       -> AutoMancing-dev.apk      (punya Hae: riwayat + REC; TIDAK masuk git; hanya jalan di HP
#                                                     yang kodenya ada di dev-devices.txt, file itu juga tidak masuk git)
#   ./build.sh publik    -> AutoMancing-publik.apk   (untuk dibagikan: pop up "buatan Hae" + teks kredit)
#   ./build.sh           -> keduanya
if [ $# -eq 0 ]; then "$0" dev && "$0" publik; exit $?; fi
VARIANT="$1"
case "$VARIANT" in dev) PUBLIK=false ;; publik) PUBLIK=true ;; *) echo "pakai: ./build.sh [dev|publik]"; exit 1 ;; esac
# dev lock: one device code per line (shown by the dev app on a phone that is not registered yet)
DEV_IDS=""
if [ "$VARIANT" = dev ] && [ -f dev-devices.txt ]; then
    DEV_IDS=$(grep -oE '^[0-9a-f]{16}' dev-devices.txt | sed 's/.*/"&"/' | paste -sd, -)
fi
OUT=build
APK=AutoMancing-$VARIANT.apk

rm -rf "$OUT"; mkdir -p "$OUT/gen/com/autofish/wibu" "$OUT/classes" "$OUT/dex"
printf 'package com.autofish.wibu;\n\n/** Generated by build.sh: which build this is. */\nfinal class Variant {\n    static final boolean PUBLIK = %s;\n    /** dev build: device codes allowed to run it (empty = none). */\n    static final String[] DEV_IDS = {%s};\n}\n' "$PUBLIK" "$DEV_IDS" > "$OUT/gen/com/autofish/wibu/Variant.java"

echo "[1/6] resources"
"$BT/aapt2" compile --dir res -o "$OUT/res.zip"
OVERLAY=()
if [ "$VARIANT" = dev ]; then # launcher name "Auto Mancing Dev"
    mkdir -p "$OUT/res-dev/values"
    printf '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <string name="app_name">Auto Mancing Dev</string>\n</resources>\n' > "$OUT/res-dev/values/strings.xml"
    "$BT/aapt2" compile --dir "$OUT/res-dev" -o "$OUT/res-dev.zip"
    OVERLAY=(-R "$OUT/res-dev.zip")
fi
"$BT/aapt2" link -o "$OUT/base.apk" -I "$JAR" --manifest AndroidManifest.xml --java "$OUT/gen" \
    --min-sdk-version 26 --target-sdk-version 34 --version-code 10 --version-name 1.9 "$OUT/res.zip" ${OVERLAY[@]+"${OVERLAY[@]}"}

echo "[2/6] javac"
javac -nowarn -Xlint:-options -source 8 -target 8 -encoding UTF-8 -bootclasspath "$JAR:$BT/core-lambda-stubs.jar" -d "$OUT/classes" \
    $(find src "$OUT/gen" -name '*.java')

echo "[3/6] d8"
"$BT/d8" --release --min-api 26 --lib "$JAR" --output "$OUT/dex" $(find "$OUT/classes" -name '*.class')

echo "[4/6] package"
cp "$OUT/base.apk" "$OUT/unsigned.apk"
(cd "$OUT/dex" && zip -q -j ../unsigned.apk classes.dex)
"$BT/zipalign" -f -p 4 "$OUT/unsigned.apk" "$OUT/aligned.apk"

echo "[5/6] sign"
if [ ! -f debug.keystore ]; then
    keytool -genkeypair -keystore debug.keystore -storepass android -keypass android -alias key \
        -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=AutoMancing" >/dev/null 2>&1
fi
"$BT/apksigner" sign --ks debug.keystore --ks-pass pass:android --key-pass pass:android --out "$APK" "$OUT/aligned.apk"
"$BT/apksigner" verify "$APK"

echo "[6/6] done ($VARIANT) -> $(pwd)/$APK"
