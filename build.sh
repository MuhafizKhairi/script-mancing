#!/bin/bash
# Build the APK with only the Android SDK command-line tools (no Gradle needed).
set -euo pipefail
cd "$(dirname "$0")"

SDK="${ANDROID_HOME:-$HOME/Library/Android/sdk}"
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
JAR="$SDK/platforms/android-36/android.jar"
[ -f "$JAR" ] || JAR="$SDK/platforms/$(ls "$SDK/platforms" | grep -E '^android-[0-9]+$' | sort -V | tail -1)/android.jar"
# Two builds from the same code:
#   ./build.sh pribadi   -> AutoMancing-pribadi.apk  (punya Hae sendiri, tanpa pop up)
#   ./build.sh publik    -> AutoMancing-publik.apk   (untuk dibagikan: pop up "buatan Hae" + teks kredit)
#   ./build.sh           -> keduanya
if [ $# -eq 0 ]; then "$0" pribadi && "$0" publik; exit $?; fi
VARIANT="$1"
case "$VARIANT" in pribadi) PUBLIK=false ;; publik) PUBLIK=true ;; *) echo "pakai: ./build.sh [pribadi|publik]"; exit 1 ;; esac
OUT=build
APK=AutoMancing-$VARIANT.apk

rm -rf "$OUT"; mkdir -p "$OUT/gen/com/autofish/wibu" "$OUT/classes" "$OUT/dex"
printf 'package com.autofish.wibu;\n\n/** Generated by build.sh: which build this is. */\nfinal class Variant {\n    static final boolean PUBLIK = %s;\n}\n' "$PUBLIK" > "$OUT/gen/com/autofish/wibu/Variant.java"

echo "[1/6] resources"
"$BT/aapt2" compile --dir res -o "$OUT/res.zip"
"$BT/aapt2" link -o "$OUT/base.apk" -I "$JAR" --manifest AndroidManifest.xml --java "$OUT/gen" \
    --min-sdk-version 26 --target-sdk-version 34 --version-code 8 --version-name 1.7 "$OUT/res.zip"

echo "[2/6] javac"
javac -nowarn -Xlint:-options -source 8 -target 8 -encoding UTF-8 -bootclasspath "$JAR:$BT/core-lambda-stubs.jar" -d "$OUT/classes" \
    $(find src "$OUT/gen" -name '*.java')

echo "[3/6] d8"
"$BT/d8" --release --min-api 26 --lib "$JAR" --output "$OUT/dex" $(find "$OUT/classes" -name '*.class')

echo "[4/6] package"
cp "$OUT/base.apk" "$OUT/unsigned.apk"
(cd "$OUT/dex" && zip -q -j ../unsigned.apk classes.dex)
"$BT/zipalign" -f -p 4 "$OUT/unsigned.apk" "$OUT/aligned.apk"

echo "[5/6] sign"
if [ ! -f debug.keystore ]; then
    keytool -genkeypair -keystore debug.keystore -storepass android -keypass android -alias key \
        -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=AutoMancing" >/dev/null 2>&1
fi
"$BT/apksigner" sign --ks debug.keystore --ks-pass pass:android --key-pass pass:android --out "$APK" "$OUT/aligned.apk"
"$BT/apksigner" verify "$APK"

echo "[6/6] done ($VARIANT) -> $(pwd)/$APK"
